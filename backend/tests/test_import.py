FIXTURES = Path(__file__).parent / "fixtures" / "imports"
NESSUS = (FIXTURES / "sample.nessus").read_bytes()
OPENVAS = (FIXTURES / "sample-openvas.xml").read_bytes()


def _project(db: Session, *targets: tuple[str, TargetType]) -> tuple[Project, list[Target]]:
    project = Project(name="Import Test")
    db.add(project)
    db.flush()
    rows = [
        Target(project_id=project.id, value=v, target_type=t, authorization_confirmed=False)
        for v, t in targets
    ]
    db.add_all(rows)
    db.commit()
    return project, rows


def _post(client: TestClient, project: Project, body: bytes):
    return client.post(
        f"/api/v1/projects/{project.id}/imports",
        content=body,
        headers={"Content-Type": "application/xml"},
    )


def _nessus_host(name: str, items: str, start: str = "Tue Nov 24 10:00:00 2026") -> str:
    return (
        f'<ReportHost name="{name}"><HostProperties>'
        f'<tag name="HOST_START">{start}</tag></HostProperties>{items}</ReportHost>'
    )


def _nessus(*hosts: str) -> bytes:
    return (
        "<NessusClientData_v2><Report name='t'>"
        + "".join(hosts)
        + "</Report></NessusClientData_v2>"
    ).encode()


# --- I1: Nessus parser --------------------------------------------------------


def test_i1_nessus_parser() -> None:
    report = parse_report(NESSUS)
    assert report.format == "nessus"
    web, db_host = report.hosts
    assert web.names == ["10.20.0.5", "10.20.0.5", "web.lab.example"]
    assert web.scan_start == datetime(2026, 11, 24, 10, 0, tzinfo=UTC)  # HOST_START_TIMESTAMP
    assert db_host.scan_start == datetime(2026, 11, 24, 11, 0, tzinfo=UTC)  # HOST_START text
    by_plugin = {r.plugin_id: r for r in web.results}
    apache = by_plugin["153584"]
    assert apache.cve_ids == ["CVE-2021-41773", "CVE-2021-42013"]  # one plugin, two CVEs
    assert (apache.severity, apache.cvss, apache.port) == ("CRITICAL", 9.8, 80)
    assert apache.cvss_vector.startswith("CVSS:3.0/")
    local = by_plugin["900001"]
    assert (local.port, local.cve_ids, local.severity) == (0, ["CVE-2022-0778"], "HIGH")
    assert set(web.ports) == {(0, "tcp"), (80, "tcp"), (22, "tcp")}
    assert report.skipped_info == 2  # the two severity-0 items
    assert report.skipped_no_cve == 1  # TRACE/TRACK: no CVE
    assert db_host.results[0].cvss == 7.2  # v2 score when no v3


# --- I2: OpenVAS parser --------------------------------------------------------


def test_i2_openvas_parser() -> None:
    report = parse_report(OPENVAS)
    assert report.format == "openvas"
    (host,) = report.hosts
    assert host.names == ["10.20.0.5", "web.lab.example"]
    assert host.scan_start == datetime(2026, 11, 24, 9, 5, tzinfo=UTC)  # the host's own start
    by_port = {r.port: r for r in host.results}
    assert by_port[80].cve_ids == ["CVE-2021-41773"]  # from <refs><ref type="cve">
    assert (by_port[80].qod, by_port[80].severity) == (99.0, "HIGH")
    assert by_port[22].cve_ids == ["CVE-2016-6210", "CVE-2016-6515"]  # legacy <cve> list
    assert by_port[22].severity == "MEDIUM"
    assert report.skipped_info == 1  # threat Log
    assert report.skipped_no_cve == 1  # NOCVE
    assert (0, "tcp") in host.ports  # general/tcp


def test_i2_get_reports_response_wrapper_and_report_level_start() -> None:
    body = (
        b"<get_reports_response><report><scan_start>2026-11-20T08:00:00Z</scan_start>"
        b"<results><result><host>10.0.0.1</host><port>443/tcp</port>"
        b"<nvt oid='1.2'><name>x</name><refs><ref type='cve' id='CVE-2020-0001'/></refs></nvt>"
        b"<threat>High</threat><severity>9.1</severity></result></results>"
        b"</report></get_reports_response>"
    )
    (host,) = parse_report(body).hosts
    assert host.scan_start == datetime(2026, 11, 20, 8, 0, tzinfo=UTC)
    assert host.results[0].severity == "CRITICAL"
    assert host.results[0].qod is None


# --- I3: hostile files -----------------------------------------------------------

XXE = b"""<?xml version="1.0"?>
<!DOCTYPE r [<!ENTITY xxe SYSTEM "file:///etc/passwd">]>
<NessusClientData_v2><Report name="&xxe;"/></NessusClientData_v2>"""

BOMB = b"""<?xml version="1.0"?>
<!DOCTYPE lolz [<!ENTITY lol "lol"><!ENTITY lol2 "&lol;&lol;&lol;&lol;&lol;&lol;&lol;&lol;">
<!ENTITY lol3 "&lol2;&lol2;&lol2;&lol2;&lol2;&lol2;&lol2;&lol2;">]>
<NessusClientData_v2><Report name="&lol3;"/></NessusClientData_v2>"""


@pytest.mark.parametrize(
    "body, message",
    [
        (XXE, "DTD"),
        (BOMB, "DTD"),
        (b"<NessusClientData_v2><Report>", "Malformed XML"),
        (b"<html><body>hi</body></html>", "Unknown report format"),
        (
            _nessus(*[_nessus_host(f"10.0.{i // 250}.{i % 250}", "") for i in range(1001)]),
            "Too many hosts",
        ),
        (_nessus(_nessus_host("10.20.0.5", "")).replace(b"HOST_START", b"OTHER"), "no scan time"),
    ],
    ids=["xxe", "entity-bomb", "malformed", "unknown-root", "host-cap", "no-scan-time"],
)
def test_i3_hostile_files_rejected_and_nothing_written(
    client: TestClient, db: Session, body: bytes, message: str
) -> None:
    project, _ = _project(db, ("10.20.0.5", TargetType.IP))
    before = db.query(Scan).count()
    resp = _post(client, project, body)
    assert resp.status_code == 400
    assert message in resp.json()["detail"]
    assert db.query(Scan).count() == before


def test_i3_oversized_body_is_413(client: TestClient, db: Session) -> None:
    project, _ = _project(db, ("10.20.0.5", TargetType.IP))
