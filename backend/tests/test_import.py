def test_i6_import_merges_with_vulnsight_item_end_to_end(
    client: TestClient, db: Session, mock_finish_import_task_delay
) -> None:
    project, (target,) = _project(db, ("10.20.0.5", TargetType.IP))
    # A VulnSight scan already tracks CVE-2021-41773 on port 80.
    s1, sv1 = _scan(db, target, {80: ["CVE-2021-41773"]})
    sync_remediation(db, s1, sv1)

    resp = _post(client, project, NESSUS)
    assert resp.status_code == 201
    body = resp.json()
    assert body["format"] == "nessus"
    assert body["findings_imported"] == 3  # 41773 + 42013 on :80, 0778 on port 0
    (entry,) = body["scans"]
    mock_finish_import_task_delay.assert_called_once_with(entry["scan_id"])

    scan = db.get(Scan, entry["scan_id"])
    assert scan.config == {"scanner": "nessus", "import": True}
    assert scan.created_at == datetime(2026, 11, 24, 10, 0, tzinfo=UTC)
    asset = db.query(Asset).filter_by(scan_id=scan.id).one()
    with (
        patch("app.modules.vulnerability.threat_intel.kev_ids", return_value={"CVE-2021-41773"}),
        patch(
            "app.modules.vulnerability.threat_intel.epss_scores",
            return_value=({"CVE-2021-41773": (0.94, 0.99)}, 0),
        ),
    ):
        _finish_scan(db, scan, asset, list(asset.services))

    db.expire_all()
    assert scan.status == ScanStatus.COMPLETED
    assert scan.threat_intel_failed == 0
    finding = (
        db.query(Finding)
        .filter(Finding.cve_id == "CVE-2021-41773", Finding.source == "nessus")
        .one()
    )
    assert finding.kev is True and finding.epss == 0.94
    assert finding.evidence["plugin_id"] == "153584"
    assert finding.confidence_score == 90.0

    items = {i.cve_id: i for i in db.query(RemediationItem).filter_by(target_id=target.id).all()}
    assert set(items) == {"CVE-2021-41773", "CVE-2021-42013", "CVE-2022-0778"}  # no duplicate
    merged = items["CVE-2021-41773"]
    assert merged.sources == ["vulnsight", "nessus"]
    assert merged.state == RemediationState.OPEN
    assert items["CVE-2022-0778"].port == 0
    assert items["CVE-2021-42013"].sources == ["nessus"]
    assert scan.risk_score is not None


